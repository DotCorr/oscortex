/// OSCortex canonical spacing scale.
///
/// Consistent spacing constants for padding, margins, and gaps
/// across all OSCortex apps.
abstract final class OscSpacing {
  /// 2px — hairline gap.
  static const double xs2 = 2;

  /// 4px — tight inner padding.
  static const double xs = 4;

  /// 6px — compact gap.
  static const double sm = 6;

  /// 8px — standard small gap.
  static const double md = 8;

  /// 10px — medium gap.
  static const double lg = 10;

  /// 12px — standard gap between cards.
  static const double xl = 12;

  /// 14px — generous card padding.
  static const double xl2 = 14;

  /// 16px — standard section padding.
  static const double xl3 = 16;

  /// 18px — large section padding.
  static const double xl4 = 18;

  /// 24px — extra-large padding.
  static const double xl5 = 24;

  /// 28px — app-level padding.
  static const double xl6 = 28;

  /// Rail / sidebar width.
  static const double railWidth = 68;

  /// Top chrome height.
  static const double chromeHeight = 44;

  /// Hub dock pill inner padding.
  static const double hubPadding = 5;
}
