//! OSCortex stub app — generic "Coming Soon" placeholder.
//!
//! Built once and copied to /bin/files, /bin/settings, /bin/editor.
//! Uses SYS_FB_MAP for direct framebuffer access.  Returns immediately
//! when the user presses any key (or after 5 s timeout via event poll).
//!
//! Compile-time env var `APP_TITLE` sets the displayed name (default "App").
#![no_std]
#![no_main]
#![allow(dead_code)]

use core::arch::asm;

core::arch::global_asm!(
    ".section .text._start",
    ".global _start",
    "_start:",
    "   xor  rbp, rbp",
    "   and  rsp, -16",
    "   call stub_main",
    "0: hlt",
    "   jmp  0b",
);

// ── Syscall numbers ───────────────────────────────────────────────────────────
const SYS_WRITE:          u64 = 1;
const SYS_EXIT:           u64 = 60;
const SYS_FB_MAP:         u64 = 0x377;
const SYS_WM_NEXT_EVENT:  u64 = 0x378;
const SYS_FB_SIZE_PACKED: u64 = 0x305;
const SYS_SCHED_YIELD:    u64 = 0x390;

// ── WmEvent (must match kernel repr(C)) ──────────────────────────────────────
#[repr(C)]
#[derive(Default)]
struct WmEvent { pub kind: u32, pub flags: u32, pub a: u64, pub b: u64 }
const EV_KEY: u32 = 3;

// ── Inline syscall helpers ───────────────────────────────────────────────────
#[inline(always)]
unsafe fn syscall1(nr: u64, a0: u64) -> i64 {
    let ret: i64;
    asm!("syscall",
        inlateout("rax") nr => ret,
        in("rdi") a0,
        lateout("rcx") _, lateout("r11") _,
        options(nostack));
    ret
}
#[inline(always)]
unsafe fn syscall0(nr: u64) -> i64 {
    let ret: i64;
    asm!("syscall",
        inlateout("rax") nr => ret,
        lateout("rcx") _, lateout("r11") _,
        options(nostack));
    ret
}

// ── Drawing helpers ──────────────────────────────────────────────────────────
unsafe fn fill_rect(fb: *mut u32, pitch: usize, x0: usize, y0: usize,
                    w: usize, h: usize, color: u32) {
    for row in y0..y0 + h {
        for col in x0..x0 + w {
            fb.add(row * pitch + col).write_volatile(color);
        }
    }
}

