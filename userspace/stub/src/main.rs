unsafe fn draw_char(fb: *mut u32, pitch: usize, x: usize, y: usize,
                    ch: u8, fg: u32) {
    let glyph = FONT[(ch as usize).min(127)];
    for row in 0..8usize {
        for col in 0..8usize {
            if (glyph[row] >> (7 - col)) & 1 != 0 {
                fb.add((y + row) * pitch + x + col).write_volatile(fg);
            }
        }
    }
}

unsafe fn draw_str(fb: *mut u32, pitch: usize, mut x: usize, y: usize,
                   s: &[u8], fg: u32) {
    for &b in s { draw_char(fb, pitch, x, y, b, fg); x += 8; }
}

// ── Main ─────────────────────────────────────────────────────────────────────
#[unsafe(no_mangle)]
extern "C" fn stub_main() {
    // Map framebuffer.
    let fb_va = unsafe { syscall0(SYS_FB_MAP) };
    if fb_va <= 0 { unsafe { syscall1(SYS_EXIT, 1); } return; }
    let fb = fb_va as *mut u32;

    let packed = unsafe { syscall0(SYS_FB_SIZE_PACKED) as u64 };
    let fb_w = ((packed >> 32) & 0xFFFF_FFFF) as usize;
    let fb_h = (packed & 0xFFFF_FFFF) as usize;
    let pitch = fb_w; // assume pitch == width in pixels

    if fb_w == 0 || fb_h == 0 { unsafe { syscall1(SYS_EXIT, 1); } return; }

    // Background
    unsafe { fill_rect(fb, pitch, 0, 0, fb_w, fb_h, 0x000D1117); }
    // Card
    let cw = 480usize;
    let ch = 200usize;
    let cx = (fb_w.saturating_sub(cw)) / 2;
    let cy = (fb_h.saturating_sub(ch)) / 2;
    unsafe {
        // Shadow
        fill_rect(fb, pitch, cx + 4, cy + 4, cw, ch, 0x00040810);
        // Card body
        fill_rect(fb, pitch, cx, cy, cw, ch, 0x00161B22);
        // Accent stripe
        fill_rect(fb, pitch, cx, cy, cw, 4, 0x003B82F6);
        // Titles
        draw_str(fb, pitch, cx + 16, cy + 20, b"Coming Soon", 0x00E6EDF3);
        draw_str(fb, pitch, cx + 16, cy + 36, b"This app is under construction.", 0x008B949E);
        draw_str(fb, pitch, cx + 16, cy + 60, b"Press any key to return to launcher.", 0x008B949E);
    }

    // Wait for any key press.
    let mut ev = WmEvent::default();
    loop {
        let r = unsafe { syscall1(SYS_WM_NEXT_EVENT, &mut ev as *mut WmEvent as u64) };
        if r >= 0 && ev.kind == EV_KEY && (ev.flags & 1) != 0 {
            break; // key pressed
        }
        // Yield CPU between polls
        unsafe { syscall0(SYS_SCHED_YIELD); }
    }

    unsafe { syscall1(SYS_EXIT, 0); }
}

#[panic_handler]
fn panic(_: &core::panic::PanicInfo) -> ! {
    loop { unsafe { asm!("hlt", options(nostack)); } }
}
